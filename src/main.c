/* Map any supported form (bare word, -X, --word) to a canonical name.
 * Returns NULL for unrecognized tokens. */
static const char *parse_command(const char *arg) {
    if (arg == NULL) return NULL;
    if (strcmp(arg, "init")     == 0 || strcmp(arg, "-I")  == 0 || strcmp(arg, "--init")   == 0) return "init";
    if (strcmp(arg, "migrate-encrypt") == 0 || strcmp(arg, "--migrate-encrypt") == 0) return "migrate-encrypt";
    if (strcmp(arg, "export") == 0 || strcmp(arg, "--export") == 0) return "export";
    if (strcmp(arg, "sql") == 0 || strcmp(arg, "--sql") == 0) return "sql";
    if (strcmp(arg, "import-plan") == 0 || strcmp(arg, "--import-plan") == 0) return "import-plan";
    if (strcmp(arg, "render")   == 0 || strcmp(arg, "-R")  == 0 || strcmp(arg, "--render")  == 0) return "render";
    if (strcmp(arg, "status")   == 0 || strcmp(arg, "-S")  == 0 || strcmp(arg, "--status")  == 0) return "status";
    if (strcmp(arg, "ls")       == 0 || strcmp(arg, "-L")  == 0 || strcmp(arg, "--ls")      == 0) return "ls";
    if (strcmp(arg, "show")     == 0 || strcmp(arg, "-SH") == 0 || strcmp(arg, "--show")    == 0) return "show";
    if (strcmp(arg, "log")      == 0 || strcmp(arg, "-LG") == 0 || strcmp(arg, "--log")     == 0) return "log";
    if (strcmp(arg, "next")     == 0 || strcmp(arg, "-N")  == 0 || strcmp(arg, "--next")    == 0) return "next";
    if (strcmp(arg, "start")    == 0 ||                              strcmp(arg, "--start")   == 0) return "start";
    if (strcmp(arg, "close")    == 0 ||                              strcmp(arg, "--close")   == 0) return "close";
    if (strcmp(arg, "cancel")   == 0 ||                              strcmp(arg, "--cancel")  == 0) return "cancel";
    if (strcmp(arg, "close-phase")  == 0 ||                          strcmp(arg, "--close-phase")  == 0) return "close-phase";
    if (strcmp(arg, "cancel-phase") == 0 ||                          strcmp(arg, "--cancel-phase") == 0) return "cancel-phase";
    if (strcmp(arg, "defer")    == 0 ||                              strcmp(arg, "--defer")   == 0) return "defer";
    if (strcmp(arg, "current")  == 0 ||                              strcmp(arg, "--current") == 0) return "current";
    if (strcmp(arg, "activate") == 0 ||                              strcmp(arg, "--activate")== 0) return "activate";
    if (strcmp(arg, "b64")      == 0 || strcmp(arg, "-B")  == 0 || strcmp(arg, "--b64")     == 0) return "b64";
    if (strcmp(arg, "usage")    == 0 || strcmp(arg, "-U")  == 0 || strcmp(arg, "--usage")   == 0) return "usage";
    if (strcmp(arg, "version")  == 0 || strcmp(arg, "-V")  == 0 || strcmp(arg, "--version") == 0) return "version";
    return NULL;
}

/* ---- internal dispatch helper ------------------------------------- */

/* Call a read op from CLI context. Caller provides a cJSON params object
 * (may be an empty object; must not be NULL). Returns the detached
 * result node on success, NULL on error (message already printed to stderr).
 * Caller owns the returned cJSON and must free it with cJSON_Delete(). */
static cJSON *call_op(sqlite3 *db, const char *op, cJSON *params) {
    ipman_request_t req;
    memset(&req, 0, sizeof req);
    /* Synthetic in-process request: bypasses ipman_request_parse, so this
     * field is informational only. Set it to the real wire version (2) so
     * any future handler that inspects it sees the same value the agent
     * envelope carries on the actual JSON-on-stdin path. */
    req.protocol_version = 2;
    req.request_id       = "cli";
    req.actor            = "cli";
    req.op               = op;
    req.params           = params;
    req.root             = NULL;

    cJSON *response = NULL;
    ipman_dispatch(&req, db, &response);
    if (response == NULL) {
        fprintf(stderr, "ipman: internal error calling %s\n", op);
        return NULL;
    }

    cJSON *ok_item = cJSON_GetObjectItemCaseSensitive(response, "ok");
    if (!cJSON_IsTrue(ok_item)) {
        cJSON *err = cJSON_GetObjectItemCaseSensitive(response, "error");
        cJSON *msg = err ? cJSON_GetObjectItemCaseSensitive(err, "message") : NULL;
        fprintf(stderr, "ipman: %s\n",
                (msg && cJSON_IsString(msg)) ? msg->valuestring : "unknown error");
        cJSON_Delete(response);
        return NULL;
    }

    cJSON *result = cJSON_DetachItemFromObjectCaseSensitive(response, "result");
    cJSON_Delete(response);
    return result;
}

/* Print the v2 protocol envelope a write verb would dispatch, then exit
 * the verb without executing it. Used by --dry-run; the printed envelope
 * is valid JSON suitable for piping into `ipman` over stdin if the user
 * decides to run it. The synthetic request_id "dry-run-<verb>" makes
 * dry-run dispatches identifiable in any downstream logs. */
static void print_dry_run_envelope(const char *op, const cJSON *params,
                                   const char *verb) {
    cJSON *envelope = cJSON_CreateObject();
    cJSON_AddNumberToObject(envelope, "protocol_version", 2);
    char rid[64];
    snprintf(rid, sizeof rid, "dry-run-%s", verb);
    cJSON_AddStringToObject(envelope, "request_id", rid);
    cJSON_AddStringToObject(envelope, "actor",      "cli");
    cJSON_AddStringToObject(envelope, "op",         op);
    cJSON_AddItemToObject(envelope, "params", cJSON_Duplicate(params, 1));

    char *s = cJSON_Print(envelope);
    if (s != NULL) {
        fprintf(stdout, "%s\n", s);
        free(s);
    }
    cJSON_Delete(envelope);
}

