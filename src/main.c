/* Embedded usage text — generated by scripts/embed_usage.sh from
 * src/usage_text.txt. Declared here because main.c is the sole caller. */
extern const unsigned char ipman_usage_text[];
extern const size_t        ipman_usage_text_len;

static int g_b64_mode = 0;
static int g_dry_run  = 0;

/* Default cap on stdin payload size (16 MiB). Overridable per-process via the
 * IPMAN_MAX_REQUEST_BYTES env var. Mitigates OWASP A04 unbounded-input risk on
 * a CLI that any agent can pipe into. */
#define IPMAN_DEFAULT_MAX_REQUEST_BYTES (16u * 1024u * 1024u)

/* Parse IPMAN_MAX_REQUEST_BYTES. Returns the configured limit; on missing,
 * empty, or unparseable values, falls back to the default and logs once. */
static size_t resolve_max_request_bytes(void) {
    const char *raw = getenv("IPMAN_MAX_REQUEST_BYTES");
    if (raw == NULL || raw[0] == '\0') {
        return IPMAN_DEFAULT_MAX_REQUEST_BYTES;
    }
    errno = 0;
    char *endp = NULL;
    unsigned long long v = strtoull(raw, &endp, 10);
    if (errno != 0 || endp == raw || (endp != NULL && *endp != '\0')) {
        ipman_log_warn("invalid IPMAN_MAX_REQUEST_BYTES; using default",
                      "value=\"%s\" default=%u", raw,
                      (unsigned)IPMAN_DEFAULT_MAX_REQUEST_BYTES);
        return IPMAN_DEFAULT_MAX_REQUEST_BYTES;
    }
    if (v > (unsigned long long)((size_t)-1)) {
        ipman_log_warn("IPMAN_MAX_REQUEST_BYTES exceeds size_t; using default",
                      "value=\"%s\"", raw);
        return IPMAN_DEFAULT_MAX_REQUEST_BYTES;
    }
    return (size_t)v;
}

static void emit_response_text(const char *json) {
    static const char encode_fail_b64[] =
        "eyJyZXF1ZXN0X2lkIjpudWxsLCJvayI6ZmFsc2UsImVycm9yIjp7ImNvZGUiOiJpbnRlcm5hbF9lcnJvciIsIm1lc3NhZ2UiOiJmYWlsZWQgdG8gZW5jb2RlIHJlc3BvbnNlIn19";

    if (g_b64_mode) {
        char *encoded = NULL;
        if (ipman_base64_encode((const unsigned char *)json, strlen(json), &encoded) != 0) {
            fputs(encode_fail_b64, stdout);
            fputc('\n', stdout);
            return;
        }
        fputs(encoded, stdout);
        fputc('\n', stdout);
        free(encoded);
        return;
    }

    fputs(json, stdout);
    fputc('\n', stdout);
}

static void emit_response(cJSON *resp) {
    if (resp == NULL) {
        /* Out-of-memory during response construction. Produce the simplest
         * possible fatal envelope by hand so callers still get valid JSON. */
        const char *fallback =
            "{\"request_id\":null,\"ok\":false,"
            "\"error\":{\"code\":\"internal_error\","
            "\"message\":\"failed to build response\"}}";
        emit_response_text(fallback);
        return;
    }
    char *s = cJSON_PrintUnformatted(resp);
    if (s == NULL) {
        const char *fallback =
            "{\"request_id\":null,\"ok\":false,"
            "\"error\":{\"code\":\"internal_error\","
            "\"message\":\"failed to serialize response\"}}";
        emit_response_text(fallback);
        return;
    }

    emit_response_text(s);
    cJSON_free(s);
}

static int emit_fatal(const char *request_id, ipman_error_code_t code,
                      const char *msg) {
    cJSON *resp = ipman_response_err(request_id, code, msg, NULL);
    emit_response(resp);
    if (resp) cJSON_Delete(resp);
    return 1;
}

/* Like emit_fatal, but honors the semantic-vs-fatal distinction in
 * ipman_error_is_fatal: validation_failed/conflict/etc. produce a JSON
 * envelope on stdout with exit code 0, matching what the JSON dispatch
 * path does. CLI verbs use this for recoverable errors so callers can
 * cleanly distinguish "binary blew up" from "operation legitimately
 * declined". */
static int emit_op_error(const char *request_id, ipman_error_code_t code,
                         const char *msg) {
    cJSON *resp = ipman_response_err(request_id, code, msg, NULL);
    emit_response(resp);
    if (resp) cJSON_Delete(resp);
    return ipman_error_is_fatal(code) ? 1 : 0;
}

/* Human-readable nudge after a malformed JSON envelope. Stdout (the JSON
 * response) is unchanged; this only writes to stderr, which programmatic
 * consumers already ignore. Scoped to ipman_request_parse failures — never
 * fired on op-level errors, where the caller's envelope was well-formed. */
static void emit_parse_error_tip(void) {
    fputs("ipman: tip — try `ipman --usage` for CLI verbs, "
          "or `ipman --next` to see the active plan\n",
          stderr);
}

static void print_usage(FILE *out) {
    fprintf(out, "ipman %s - Implementation Plan Manager\n", IPMAN_VERSION);
    fwrite(ipman_usage_text, 1, ipman_usage_text_len, out);
}

static int build_db_path(const char *home, char *dbpath, size_t dbpath_len) {
    int n = snprintf(dbpath, dbpath_len, "%s/ipman.db", home);
    if (n < 0 || (size_t)n >= dbpath_len) {
        ipman_log_error("db path too long", "home=%s", home);
        return -1;
    }
    return 0;
}

static int open_workspace(sqlite3 **db_out, char *home, size_t home_len,
                          char *dbpath, size_t dbpath_len,
                          int create, int *schema_version_out) {
    if (ipman_home_resolve(home, home_len) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL, "cannot resolve ipman home");
    }
    if (create) {
        if (ipman_home_ensure(home) != 0) {
            return emit_fatal(NULL, IPMAN_ERR_INTERNAL,
                              "cannot prepare ipman home");
        }
        if (ipman_keysalt_ensure(home) != 0) {
            return emit_fatal(NULL, IPMAN_ERR_INTERNAL,
                              "cannot prepare keysalt");
        }
    } else if (ipman_home_require(home) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL,
                          "ipman workspace is not initialized; run `ipman init`");
    }

    if (build_db_path(home, dbpath, dbpath_len) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL, "db path too long");
    }
    if (!create && access(dbpath, F_OK) != 0) {
        ipman_log_error("ipman database missing", "path=%s", dbpath);
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL,
                          "ipman workspace is not initialized; run `ipman init`");
    }

    sqlite3 *db = NULL;
    int db_rc = create ? ipman_db_open(home, dbpath, &db)
                       : ipman_db_open_existing(home, dbpath, &db);
    if (db_rc != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL, "cannot open database");
    }

    int schema_version = 0;
    if (ipman_migrations_apply(db, dbpath, &schema_version) != 0) {
        ipman_db_close(db);
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL, "migration apply failed");
    }

    if (ipman_agent_docs_refresh(home, dbpath, NULL) != 0) {
        ipman_db_close(db);
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL,
                          "agent docs generation failed");
    }

    *db_out = db;
    if (schema_version_out != NULL) *schema_version_out = schema_version;
    return 0;
}

static int run_render(const char *selector) {
    char home[PATH_MAX];
    char dbpath[PATH_MAX];
    sqlite3 *db = NULL;
    int rc = open_workspace(&db, home, sizeof home, dbpath, sizeof dbpath,
                            0, NULL);
    if (rc != 0) return rc;

    sqlite3_int64 plan_id = 0;
    if (ipman_render_resolve_plan(db, selector, &plan_id) != 0) {
        fprintf(stderr, "ipman render: plan not found: %s\n", selector);
        ipman_db_close(db);
        return 1;
    }

    int render_rc = ipman_render_md(db, plan_id, stdout);
    ipman_db_close(db);
    return render_rc != 0 ? 1 : 0;
}

/*
 * On first init, the project row is seeded with name='unnamed' by migration
 * 0004. We can do better than that: the parent directory of IPMAN_HOME
 * almost always *is* the repo, so its basename is the natural project name.
 *
 * Behavior:
 *   - Resolves IPMAN_HOME to an absolute path with realpath().
 *   - Takes the basename of the parent directory (e.g. for ".ipman" inside
 *     a repo named "myapp", the parent is "myapp").
 *   - Updates the row only if name is still the literal default 'unnamed';
 *     never overwrites a user-supplied name.
 *
 * Failures here are non-fatal (we silently leave the default in place);
 * this is best-effort ergonomics, not a correctness requirement.
 */
static void auto_name_project_if_default(sqlite3 *db, const char *home) {
    /* Build an absolute path for `home` without relying on realpath() —
     * which is only declared under feature-test macros our build does
     * not enable. For relative paths, prepend cwd; for absolute paths
     * use as-is. We do not need symlink resolution here. */
    char abs[PATH_MAX];
    if (home[0] == '/') {
        int n = snprintf(abs, sizeof abs, "%s", home);
        if (n < 0 || (size_t)n >= sizeof abs) return;
    } else {
        char cwd[PATH_MAX];
        if (getcwd(cwd, sizeof cwd) == NULL) return;
        int n = snprintf(abs, sizeof abs, "%s/%s", cwd, home);
        if (n < 0 || (size_t)n >= sizeof abs) return;
    }

    /* dirname() and basename() may mutate their input; always use copies.
     *
     * Heuristic: if the home directory itself is `.ipman` (the default
     * convention from ipman_home.c — the workspace lives inside the repo),
     * the project name comes from the *parent* directory's basename. Any
     * other path means IPMAN_HOME was set explicitly, so we treat the
     * home directory itself as the project root and use its own basename. */
    char buf_for_base[PATH_MAX];
    int n = snprintf(buf_for_base, sizeof buf_for_base, "%s", abs);
    if (n < 0 || (size_t)n >= sizeof buf_for_base) return;
    char *home_basename = basename(buf_for_base);
    if (home_basename == NULL) return;

    char *base;
    char buf_for_parent[PATH_MAX];
    char buf_for_parent_base[PATH_MAX];
    if (strcmp(home_basename, ".ipman") == 0) {
        n = snprintf(buf_for_parent, sizeof buf_for_parent, "%s", abs);
        if (n < 0 || (size_t)n >= sizeof buf_for_parent) return;
        char *parent = dirname(buf_for_parent);
        if (parent == NULL) return;
        n = snprintf(buf_for_parent_base, sizeof buf_for_parent_base,
                     "%s", parent);
        if (n < 0 || (size_t)n >= sizeof buf_for_parent_base) return;
        base = basename(buf_for_parent_base);
    } else {
        base = home_basename;
    }
    if (base == NULL || *base == '\0' ||
        strcmp(base, "/") == 0 || strcmp(base, ".") == 0) {
        return;
    }

    const char *sql =
        "UPDATE project SET "
        "name = ?, "
        "updated_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now') "
        "WHERE id = 1 AND name = 'unnamed';";
    sqlite3_stmt *stmt = NULL;
    if (sqlite3_prepare_v2(db, sql, -1, &stmt, NULL) != SQLITE_OK) return;
    sqlite3_bind_text(stmt, 1, base, -1, SQLITE_TRANSIENT);
    (void)sqlite3_step(stmt);
    sqlite3_finalize(stmt);
}

static int run_init(void) {
    /* Refuse `init` when cwd is inside a git repo but is NOT the repo
     * root. This is the silent-fork hazard the workspace discovery
     * upgrade in v2.4.2 closes: an agent in a subdir or worktree subdir
     * who runs `ipman init` would otherwise plant a stray .ipman/
     * alongside cwd, divorced from the data the user actually cares
     * about. The check is skipped when IPMAN_HOME is set explicitly
     * (operator escape hatch) and when we are not inside any repo at
     * all (legacy ad-hoc use). */
    char rel_root[PATH_MAX];
    if (ipman_home_repo_root_relpath(rel_root, sizeof rel_root) == 0 &&
        strcmp(rel_root, ".") != 0) {
        char msg[PATH_MAX + 200];
        snprintf(msg, sizeof msg,
                "init must run at the repo root (\"%s\" relative to cwd), "
                "not from a subdir or worktree subdir; cd to the root or "
                "set IPMAN_HOME explicitly to override",
                rel_root);
        return emit_op_error(NULL, IPMAN_ERR_VALIDATION_FAILED, msg);
    }

    char home[PATH_MAX];
    char dbpath[PATH_MAX];
    sqlite3 *db = NULL;
    int schema_version = 0;
    int rc = open_workspace(&db, home, sizeof home, dbpath, sizeof dbpath,
                            1, &schema_version);
    if (rc != 0) return rc;

    /* Populate the project row with the repo's directory basename when the
     * row is still its 'unnamed' default. Cheap ergonomics for first init. */
    auto_name_project_if_default(db, home);

    /* Best-effort: make the workspace-local skill discoverable for Claude
     * Code and Codex when the corresponding global install is absent. Failure
     * is logged but does not fail init — the workspace remains usable. */
    (void)ipman_skill_install();

    cJSON *result = cJSON_CreateObject();
    if (result != NULL) {
        cJSON_AddBoolToObject(result, "initialized", 1);
        cJSON_AddStringToObject(result, "home", home);
        cJSON_AddStringToObject(result, "db_path", dbpath);
        cJSON_AddNumberToObject(result, "schema_version", schema_version);
    }
    cJSON *resp = ipman_response_ok(NULL, result);
    emit_response(resp);
    if (resp) cJSON_Delete(resp);
    ipman_db_close(db);
    return 0;
}

static int run_migrate_encrypt(void) {
    char home[PATH_MAX];
    if (ipman_home_resolve(home, sizeof home) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL, "cannot resolve ipman home");
    }
    if (ipman_home_require(home) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL,
                          "ipman workspace is not initialized; run `ipman init` first");
    }
    /* Ensure the keysalt exists before deriving — for workspaces that pre-date
     * the encryption work, this generates it on first migrate. */
    if (ipman_keysalt_ensure(home) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL, "cannot prepare keysalt");
    }
    if (ipman_migrate_encrypt(home) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL, "migrate-encrypt failed");
    }
    return 0;
}

/* Parse `ipman export --plaintext --i-understand <output>` argv (argv[1] is
 * already known to be the export verb). Order of the two flags is free, but
 * both are required; <output> is the lone positional. Mismatches print a
 * usage line on stderr and return non-zero. */
static int run_export(int argc, char **argv) {
    int saw_plaintext = 0;
    int saw_understand = 0;
    const char *out_path = NULL;
    for (int i = 2; i < argc; ++i) {
        if (strcmp(argv[i], "--plaintext") == 0) {
            saw_plaintext = 1;
        } else if (strcmp(argv[i], "--i-understand") == 0) {
            saw_understand = 1;
        } else if (argv[i][0] == '-') {
            fprintf(stderr, "ipman export: unknown flag: %s\n", argv[i]);
            return 1;
        } else if (out_path == NULL) {
            out_path = argv[i];
        } else {
            fprintf(stderr, "ipman export: unexpected extra argument: %s\n",
                    argv[i]);
            return 1;
        }
    }
    if (!saw_plaintext) {
        fprintf(stderr,
                "ipman export: --plaintext is required (no other modes yet)\n");
        return 1;
    }
    if (!saw_understand) {
        fprintf(stderr,
                "ipman export --plaintext: refused without --i-understand.\n"
                "This writes an unencrypted copy of your DB; pass\n"
                "  --i-understand to acknowledge.\n");
        return 1;
    }
    if (out_path == NULL) {
        fprintf(stderr,
                "usage: ipman export --plaintext --i-understand <output.db>\n");
        return 1;
    }

    char home[PATH_MAX];
    if (ipman_home_resolve(home, sizeof home) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL, "cannot resolve ipman home");
    }
    if (ipman_home_require(home) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL,
                          "ipman workspace is not initialized; run `ipman init` first");
    }
    if (ipman_export_plaintext(home, out_path) != 0) {
        return emit_fatal(NULL, IPMAN_ERR_INTERNAL, "export --plaintext failed");
    }
    return 0;
}

/* Parse `ipman import-plan <file.json>` argv (argv[1] is already known to be
 * the import-plan verb). The sole positional argument is the JSON file path. */
static int run_import_plan(int argc, char **argv) {
    const char *json_path = NULL;
    for (int i = 2; i < argc; ++i) {
        if (argv[i][0] == '-') {
            fprintf(stderr, "ipman import-plan: unknown flag: %s\n", argv[i]);
            return 1;
        } else if (json_path == NULL) {
            json_path = argv[i];
        } else {
            fprintf(stderr, "ipman import-plan: unexpected extra argument: %s\n",
                    argv[i]);
            return 1;
        }
    }
    if (json_path == NULL) {
        fprintf(stderr, "usage: ipman import-plan <export.json>\n");
        return 1;
    }

    char home[PATH_MAX], dbpath[PATH_MAX];
    sqlite3 *db = NULL;
    int ws_rc = open_workspace(&db, home, sizeof home, dbpath, sizeof dbpath,
                               0, NULL);
    if (ws_rc != 0) return ws_rc;

    sqlite3_int64 new_plan_id = 0;
    char *err_msg = NULL;
    int rc = ipman_import_plan_envelope(db, json_path, &new_plan_id, &err_msg);
    ipman_db_close(db);

    if (rc != 0) {
        fprintf(stderr, "ipman import-plan: %s\n",
                err_msg ? err_msg : "import failed");
        free(err_msg);
        return 1;
    }
    free(err_msg);
    fprintf(stdout, "imported plan %lld\n", (long long)new_plan_id);
    return 0;
}

/* Developer / test escape-hatch: open the workspace through the standard
 * keyed open and run ad-hoc SQL. Output format mirrors `sqlite3` defaults
 * (one row per line, '|' between columns) so this drops in for tests that
 * previously called `sqlite3 "$DB" "..."`. Single SQL string as positional
 * argv. Errors land on stderr; rows on stdout. */
static int run_sql_cmd(int argc, char **argv) {
    const char *sql = NULL;
    for (int i = 2; i < argc; ++i) {
        if (argv[i][0] == '-' && argv[i][1] != '\0') {
            fprintf(stderr, "ipman sql: unknown flag: %s\n", argv[i]);
            return 1;
        } else if (sql == NULL) {
            sql = argv[i];
        } else {
            fprintf(stderr, "ipman sql: only one SQL string is supported "
                            "(got extra: %s)\n", argv[i]);
            return 1;
        }
    }
    if (sql == NULL) {
        fprintf(stderr, "usage: ipman sql \"SQL statement\"\n");
        return 1;
    }

    char home[PATH_MAX], dbpath[PATH_MAX];
    sqlite3 *db = NULL;
    int ws_rc = open_workspace(&db, home, sizeof home,
                               dbpath, sizeof dbpath, 0, NULL);
    if (ws_rc != 0) return ws_rc;

    int sql_rc = ipman_sql_run(db, sql, stdout);
    ipman_db_close(db);
    return sql_rc != 0 ? 1 : 0;
}

